"""Автоопределение отчества по имени отца.

Русская патронимика: Иван → Иванович/Ивановна, Дмитрий → Дмитриевич,
Николай → Николаевна, Никита → Никитич, Яков → Яковлевич, Лев → Львович.
Приёмные дети и сознательные отклонения не трогаем: отчество подставляется
только когда оно пустое, существующее никогда не перезаписывается.
"""
from __future__ import annotations

# исключения из общих правил: имя → основа отчества
_STEM_EXCEPTIONS = {
    "яков": "яковле",      # Яковлевич / Яковлевна
    "лев": "льво",         # Львович / Львовна
    "павел": "павло",      # Павлович / Павловна
    "гавриил": "гаврило",  # Гаврилович / Гавриловна
    "михаил": "михайло",   # Михайлович / Михайловна
    "даниил": "данило",    # Данилович / Даниловна
}


def patronymic_from_father(father_name: str, child_gender: str) -> str | None:
    """Отчество ребёнка по имени отца и полу ребёнка. None — если не выводится."""
    name = (father_name or "").strip().lower().replace("ё", "е")
    if not name or child_gender not in ("male", "female"):
        return None

    male = child_gender == "male"

    if name in _STEM_EXCEPTIONS:
        raw = _STEM_EXCEPTIONS[name] + ("вич" if male else "вна")
    elif name.endswith("я"):  # Илья → Ильич/Ильинична
        raw = name[:-1] + ("ич" if male else "инична")
    elif name.endswith("а"):  # Никита → Никитич/Никитична
        raw = name[:-1] + ("ич" if male else "ична")
    elif name.endswith("ий"):
        # Василий → Васильевич, Аркадий → Аркадьевич, Евгений → Евгеньевна:
        # «ий» выпадает, основа смягчается мягким знаком.
        # Дмитрий — исключение (Дмитриевич, без знака).
        stem = name[:-2]
        raw = stem + ("иевич" if stem == "дмитр" and child_gender == "male" else
                      "иевна" if stem == "дмитр" else
                      ("ьевич" if child_gender == "male" else "ьевна"))
    elif name.endswith("ь") or name.endswith("й"):
        # Николай → Николаевич, Сергей → Сергеевич, Алексей → Алексеевич
        raw = name[:-1] + "е" + ("вич" if male else "вна")
    else:  # прочие согласные: Иван → Иванович/Ивановна
        raw = name + ("ович" if male else "овна")
    return raw.capitalize()
